dia_semana = int(input('digite um número'))
if dia_semana == 1:
    print('domingo')
elif dia_semana == 2:
    print('segunda')
elif dia_semana == 3:
    print('terça')
elif dia_semana == 4:
    print('quarta')
elif dia_semana == 5:
    print('quinta')
elif dia_semana == 6:
    print('sexta')
elif dia_semana == 7:
    print('sábado')
else:
    print('dia da semana não existe')